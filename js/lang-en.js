/**
 * Government Office · English words (citymeter-shell, js/shell/i18n.js), keyed by the Thai the page shows. A draft
 * translation from the Thai source, not yet reviewed (demo-platform-review §5.8); the page says so. Office, place,
 * agency and station names are not here: js/lang.js registers the English the data carries, and a name without
 * English stays Thai (the dataset gives none for its offices and places).
 * Terms: หน่วยงาน = offices (government offices); สถานที่ = places (education, religion, community); แห่ง = places (one
 * production point each, “1 จุดของ production = 1 แห่ง”); บุคลากร = staff (the staff production records at an office,
 * never a capacity); หมวด = category; ประเภท = type; ต้นสังกัด = parent agency; บริการรัฐที่ใกล้ที่สุด = nearest public
 * services; ย้ายและเปิดใหม่ = moves and openings; เขต/อำเภอ = district.
 */
const N = '([\\d,]+)';
const places = (t, n) => `${n} ${t.plural(n, 'place', 'places')}`;
const offices = (t, n) => `${n} ${t.plural(n, 'office', 'offices')}`;
const staff = (t, n) => `${n} ${t.plural(n, 'staff member', 'staff')}`;
/** "N แห่ง" or "N คน" (a measure's unit after its number) → English. */
const unitOf = (t, n, unit) => (unit === 'คน' ? staff(t, n) : places(t, n));
const U = '(แห่ง|คน)';
const AREA = '(?:เขต\\/อำเภอ|เขต|อำเภอ)';
const re = source => new RegExp(`^${source}$`);
/** A text that translate() splits into parts (a pattern must not swallow it whole). */
const SPLIT = / (?:·|—|\||›) /;
/** What a view counts (js/model.js unitFor): the scope's words, a group's noun, a type's name. */
const SUBJECTS = {
  'หน่วยงาน': 'offices', 'หน่วยงานรัฐ': 'government offices', 'หน่วยงานและสถานที่': 'offices and places', 'สถานที่': 'places',
  'บุคลากร': 'staff', 'บุคลากรที่บันทึก': 'recorded staff',
};
const subject = (t, th) => SUBJECTS[th] ?? (t.part(th) == null ? null : t.part(th).toLowerCase());
/** "เขตคลองเตย กรุงเทพมหานคร" or "อำเภอถลาง" → "Khlong Toei, Bangkok" / "Thalang"; the Thai part when unknown. */
function place(t, text) {
  const s = text.trim();
  const whole = t.known(s);
  if (whole) return whole;
  const i = s.lastIndexOf(' ');
  if (i > 0) {
    const a = t.known(s.slice(0, i)), b = t.known(s.slice(i + 1));
    if (a && b) return `${a}, ${b}`;
  }
  return t.name(s);
}
